#!/usr/bin/env node
/**
 * Remove Claude Code attribution/session suffixes from messages the authenticated user
 * owns on one pull request. The default is a dry run; --apply performs updates.
 *
 * Usage: node infra/dev/clean-claude-attribution.mjs <pr-number> [--apply]
 */

import { execFileSync } from 'node:child_process';
import { parseArgs } from 'node:util';
import { pathToFileURL } from 'node:url';

const DEFAULT_REPO = 'alaiba/arcogine';
const API_ROOT = 'https://api.github.com';

function usage() {
  return `clean-claude-attribution -- remove Claude Code attribution from one pull request

USAGE
  node infra/dev/clean-claude-attribution.mjs <pr-number> [--repo owner/name] [--apply]

OPTIONS
  --repo <owner/name>  Repository (default: ${DEFAULT_REPO})
  --apply              Update messages. Without it, report proposed changes only.
  --help               Show this help.

SCOPE
  Inspects the PR description, conversation comments, review summaries, and inline review
  comments. Only messages authored by the authenticated GitHub account are eligible.
  It removes only a Claude Code generated-by footer, including its paired session trailer
  when present; all preceding text and whitespace are preserved exactly.

AUTH
  Uses GH_TOKEN or GITHUB_TOKEN, otherwise obtains a token once with \`gh auth token\`.
`;
}

export function cleanClaudeAttribution(body) {
  if (typeof body !== 'string') throw new TypeError('message body must be a string');

  // PR descriptions emitted by Claude Code have a longer final block than comments.
  // Match only a suffix, including its leading separators, to leave the authored prefix
  // byte-for-byte unchanged.
  const generatedBlock = /\n\n🤖 Generated with \[Claude Code\]\(https:\/\/claude\.com\/claude-code\)\n\nhttps:\/\/claude\.ai\/code(?:\/[^\s]+)?\n\n---\n_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code(?:\/[^\s]+)?\)_\s*$/u;
  const generatedFooter = /\n\n---\n_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code(?:\/[^\s]+)?\)_\s*$/u;

  return body.replace(generatedBlock, '').replace(generatedFooter, '');
}

function resolveToken() {
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  if (token?.trim()) return token.trim();
  try {
    return execFileSync('gh', ['auth', 'token'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    throw new Error('no GitHub token: set GH_TOKEN/GITHUB_TOKEN or authenticate the gh CLI');
  }
}

function requireRepo(repo) {
  if (!/^[^/]+\/[^/]+$/.test(repo)) throw new Error(`--repo must be owner/name, got "${repo}"`);
}

function linkNext(response) {
  const value = response.headers.get('link') ?? '';
  return value.match(/<([^>]+)>;\s*rel="next"/)?.[1] ?? null;
}

export async function githubRequest(fetchImpl, token, path, { method = 'GET', body } = {}) {
  const response = await fetchImpl(path.startsWith('http') ? path : `${API_ROOT}/${path}`, {
    method,
    headers: {
      accept: 'application/vnd.github+json',
      authorization: `Bearer ${token}`,
      ...(body === undefined ? {} : { 'content-type': 'application/json' }),
    },
    ...(body === undefined ? {} : { body: JSON.stringify(body) }),
  });
  if (!response.ok) throw new Error(`GitHub API ${method} ${path} failed: HTTP ${response.status}`);
  return { data: await response.json(), next: linkNext(response) };
}

async function paginatedRequest(fetchImpl, token, path) {
  const items = [];
  let next = path;
  while (next) {
    const page = await githubRequest(fetchImpl, token, next);
    if (!Array.isArray(page.data)) throw new Error(`GitHub API ${next} did not return an array`);
    items.push(...page.data);
    next = page.next;
  }
  return items;
}

function message(kind, id, body, author) {
  return { kind, id, body, author: author?.login ?? null };
}

async function findMessages(fetchImpl, token, repo, number) {
  const pr = await githubRequest(fetchImpl, token, `repos/${repo}/pulls/${number}`);
  const [comments, reviews, reviewComments] = await Promise.all([
    paginatedRequest(fetchImpl, token, `repos/${repo}/issues/${number}/comments?per_page=100`),
    paginatedRequest(fetchImpl, token, `repos/${repo}/pulls/${number}/reviews?per_page=100`),
    paginatedRequest(fetchImpl, token, `repos/${repo}/pulls/${number}/comments?per_page=100`),
  ]);
  return [
    message('description', number, pr.data.body ?? '', pr.data.user),
    ...comments.map((item) => message('comment', item.id, item.body ?? '', item.user)),
    ...reviews.map((item) => message('review', item.id, item.body ?? '', item.user)),
    ...reviewComments.map((item) => message('inline comment', item.id, item.body ?? '', item.user)),
  ];
}

function updatePath(repo, number, item) {
  if (item.kind === 'description') return { method: 'PATCH', path: `repos/${repo}/pulls/${number}` };
  if (item.kind === 'comment') return { method: 'PATCH', path: `repos/${repo}/issues/comments/${item.id}` };
  if (item.kind === 'review') return { method: 'PUT', path: `repos/${repo}/pulls/${number}/reviews/${item.id}` };
  return { method: 'PATCH', path: `repos/${repo}/pulls/comments/${item.id}` };
}

export async function cleanPullRequest({
  number,
  repo = DEFAULT_REPO,
  apply = false,
  fetchImpl = fetch,
  token = resolveToken(),
  log = console.log,
}) {
  if (!Number.isInteger(number) || number <= 0) throw new Error(`invalid PR number: ${number}`);
  requireRepo(repo);

  const viewer = await githubRequest(fetchImpl, token, 'user');
  const messages = await findMessages(fetchImpl, token, repo, number);
  const changes = messages
    .filter((item) => item.author === viewer.data.login)
    .map((item) => ({ ...item, cleaned: cleanClaudeAttribution(item.body) }))
    .filter((item) => item.cleaned !== item.body);

  if (!changes.length) {
    log(`PR #${number}: no Claude Code attribution found in messages authored by ${viewer.data.login}.`);
    return { changed: 0, applied: apply };
  }

  for (const item of changes) {
    const target = updatePath(repo, number, item);
    if (apply) {
      const result = await githubRequest(fetchImpl, token, target.path, {
        method: target.method,
        body: { body: item.cleaned },
      });
      if (result.data.body !== item.cleaned) {
        throw new Error(`${item.kind} ${item.id} was not preserved exactly after update`);
      }
    }
    log(`${apply ? 'Cleaned' : 'Would clean'} ${item.kind} ${item.id}.`);
  }
  log(`${apply ? 'Cleaned' : 'Would clean'} ${changes.length} message(s) on PR #${number}.`);
  return { changed: changes.length, applied: apply };
}

function parseCli(argv) {
  const { values, positionals } = parseArgs({
    args: argv,
    options: {
      repo: { type: 'string', default: DEFAULT_REPO },
      apply: { type: 'boolean', default: false },
      help: { type: 'boolean', default: false },
    },
    allowPositionals: true,
    strict: true,
  });
  if (values.help) return { help: true };
  if (positionals.length !== 1 || !/^\d+$/.test(positionals[0])) throw new Error(usage());
  return { number: Number(positionals[0]), repo: values.repo, apply: values.apply };
}

async function main() {
  const options = parseCli(process.argv.slice(2));
  if (options.help) {
    console.log(usage());
    return;
  }
  await cleanPullRequest(options);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
